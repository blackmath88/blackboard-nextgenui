'use strict';
const assert = require('assert/strict');
const { browserSupport } = require('./lib/browser');
const { verdict } = require('./lib/check-verdict');
const probe = options => browserSupport({ env: { PATH: '/bin:/test' }, platform: 'linux', websocket: true, executable: p => p === '/test/chromium', ...options });
assert.equal(probe().chrome, '/test/chromium');
assert.equal(probe({ env: { CHROME: '/missing', PATH: '/test' } }).status, 'error');
assert.equal(probe({ env: { CHROME: 'chromium', PATH: '/test' } }).chrome, '/test/chromium');
assert.equal(probe({ executable: () => false }).status, 'skip');
assert.equal(probe({ websocket: false }).status, 'skip');
assert.equal(probe({ platform: 'darwin', executable: p => p === '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' }).status, 'ready');
assert.equal(verdict('check', 0, 'ALL CHECKS PASSED').status, 'PASS');
assert.equal(verdict('check', 1, 'ALL CHECKS PASSED').status, 'FAIL');
assert.equal(verdict('check', 0, 'FAIL assertion\nALL CHECKS PASSED').status, 'FAIL');
assert.equal(verdict('check', 0, 'SKIP browser\nALL CHECKS PASSED').status, 'PARTIAL');
assert.equal(verdict('check', 77, 'SKIP browser').status, 'SKIP');
assert.equal(verdict('check', 0, 'unfinished output').status, 'FAIL');
assert.equal(verdict('verify-p0.sh', 0, '{"role":"assistant"}').status, 'FAIL');
assert.equal(verdict('verify-p0.sh', 1, '{"role":"assistant"}').status, 'FAIL');
console.log('PASS Linux/macOS browser discovery; invalid overrides fail; skips, incomplete runs and nonzero exits stay distinct');
console.log('ALL HARNESS CHECKS PASSED');
